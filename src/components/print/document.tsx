import "server-only";
import type { ReactNode } from "react";
import { StrataMark } from "@/components/brand";
import { PrintToolbar } from "@/app/print/print-toolbar";
import { brandProps, getBranding } from "@/core/branding";
import { formatDateTime } from "@/core/format";
import { getSettings } from "@/core/settings";

// The frame every printed document shares: toolbar, branded letterhead, the document's own body,
// signature lines and a footer saying who printed it and when.

export type Fact = { label: string; value: ReactNode };

export async function PrintDocument({
  title,
  number,
  status,
  copyLabel,
  party,
  facts,
  children,
  signatures = [],
  printedBy,
  disclaimer,
}: {
  /** Document name, e.g. "Sales invoice". */
  title: string;
  number: string;
  /** e.g. "Void" — shown as a red stamp. */
  status?: string;
  /** e.g. "Internal copy" — a grey stamp. */
  copyLabel?: string;
  party?: { label: string; name: string; lines?: string[] };
  facts: Fact[];
  children: ReactNode;
  /** Signature boxes: role under the line, optional name printed on it. */
  signatures?: { role: string; name?: string }[];
  printedBy: string;
  disclaimer?: string;
}) {
  const [brand, settings] = await Promise.all([getBranding(), getSettings()]);
  const { logoUrl } = brandProps(brand);
  const contact = [
    settings["company.address"],
    [settings["company.tin"] && `TIN ${settings["company.tin"]}`, settings["company.phone"], settings["company.email"]].filter(Boolean).join(" · "),
  ].filter(Boolean);

  return (
    <>
      <PrintToolbar title={`${title} ${number}`} />
      <article className="sheet">
        <header className="lh">
          <div className="lh-company">
            {logoUrl ? (
              // eslint-disable-next-line @next/next/no-img-element -- served by our own route, any size/format
              <img src={logoUrl} alt="" className="lh-logo" />
            ) : (
              <StrataMark tile size={52} />
            )}
            <div>
              <p className="lh-name">{settings["company.name"]}</p>
              <div className="lh-lines">{contact.join("\n")}</div>
            </div>
          </div>
          <div className="lh-doc">
            <h1 className="lh-title">{title}</h1>
            <div className="lh-number">{number}</div>
            {status && <div className="stamp void">{status}</div>}
            {copyLabel && <div className="stamp copy">{copyLabel}</div>}
          </div>
        </header>

        <section className="facts">
          {party ? (
            <div className="party">
              <h3>{party.label}</h3>
              <div className="who">{party.name}</div>
              {party.lines && party.lines.filter(Boolean).length > 0 && <div className="lines">{party.lines.filter(Boolean).join("\n")}</div>}
            </div>
          ) : (
            <div />
          )}
          <dl className="meta">
            {facts.map((f) => (
              <div key={f.label}>
                <dt>{f.label}</dt>
                <dd>{f.value}</dd>
              </div>
            ))}
          </dl>
        </section>

        {children}

        {signatures.length > 0 && (
          <section className="signs" style={{ "--signs": signatures.length } as React.CSSProperties}>
            {signatures.map((s) => (
              <div className="sign" key={s.role}>
                <div className="name">{s.name ?? ""}</div>
                <div className="role">{s.role}</div>
              </div>
            ))}
          </section>
        )}

        <footer className="doc-foot">
          {disclaimer && <span className="disclaimer">{disclaimer}</span>}
          <span>
            Printed {formatDateTime(new Date())} by {printedBy} · System-generated by {brand.name}
          </span>
        </footer>
      </article>
    </>
  );
}

/** Label / amount rows under a line table; the last row can be the grand total. */
export function Totals({ rows }: { rows: { label: string; value: string; grand?: boolean }[] }) {
  return (
    <table className="totals">
      <tbody>
        {rows.map((r) => (
          <tr key={r.label} className={r.grand ? "grand" : undefined}>
            <td>{r.label}</td>
            <td>{r.value}</td>
          </tr>
        ))}
      </tbody>
    </table>
  );
}

export function Words({ label = "Amount in words", children }: { label?: string; children: ReactNode }) {
  return (
    <div className="words">
      <b>{label}</b>
      {children}
    </div>
  );
}

